"""Guards on the contract between pyproject.toml, the generated requirements
files, and the commands that generate them.

These are not characterisation tests. They pin two defects that succeeded while
doing the wrong thing, and would both have returned on the next regeneration.

1. ``requirements/requirements-dev.txt`` pinned black, ruff and watchdog and no
   test runner at all. It is compiled with ``--extra dev``, while pytest and its
   plugins live in a separate ``test`` extra, so the generator never had a
   reason to include them. ``docs/contributing.md`` hands a contributor
   ``pip install -r requirements/requirements-dev.txt`` and then ``make test``
   under the heading "Verify setup"; on a clean venv that second line died with
   ``ModuleNotFoundError: No module named 'pytest'``.

2. Both generators passed ``--universal`` without ``--python-version``.
   ``--universal`` resolves for every *platform*, but on the Python axis it
   resolves from the interpreter running uv upwards rather than from
   ``requires-python``. Run on a 3.12 machine it replaced the committed
   ``numpy==2.4.6 ; python_full_version < '3.12'`` / ``numpy==2.5.4 ;
   python_full_version >= '3.12'`` pair with a bare ``numpy==2.5.4``, which has
   no 3.11 release — leaving the artifact uninstallable on the floor
   ``requires-python`` declares and CI pins.

Neither was visible to CI, which installs ``-e ".[test,dev]"`` and never reads
these files. That is the same blind spot that kept a vulnerable urllib3 pin in
``uv.lock`` (#163): a green CI run proves nothing about these artifacts, so the
check has to live here.

Each rule is read off the files rather than hand-listed, so adding a dependency
or an extra needs no edit to this module. The last three tests exist only to
stop the others passing on nothing.
"""

import re
import tomllib
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PYPROJECT = REPO_ROOT / "pyproject.toml"
REQUIREMENTS = REPO_ROOT / "requirements" / "requirements.txt"
REQUIREMENTS_DEV = REPO_ROOT / "requirements" / "requirements-dev.txt"

# The two places that regenerate the files above. Both must agree, because
# whichever one a contributor reaches for decides what lands in the tree.
GENERATORS = (
    REPO_ROOT / "Makefile",
    REPO_ROOT / "scripts" / "update-requirements.sh",
)

# A pinned line in a compiled requirements file: `name==version` optionally
# followed by an environment marker. Anchored at the start of the line so the
# indented `# via ...` provenance comments are not read as pins.
PIN = re.compile(r"^([A-Za-z0-9._-]+)==([^\s;]+)", re.MULTILINE)

# A `uv pip compile` invocation, captured to the end of its line. Matches in the
# Makefile (tab-indented recipe lines) and in the shell script alike.
COMPILE_COMMAND = re.compile(r"uv pip compile[^\n]*")


def normalise(name: str) -> str:
    """PEP 503 normalisation, so `yt-dlp`, `yt_dlp` and `YT-DLP` compare equal."""
    return re.sub(r"[-_.]+", "-", name).lower()


def pyproject() -> dict:
    return tomllib.loads(PYPROJECT.read_text(encoding="utf-8"))


def declared(*, extra: str | None = None) -> set[str]:
    """The distribution names pyproject declares, core or in one extra."""
    project = pyproject()["project"]
    entries = (
        project["dependencies"]
        if extra is None
        else project["optional-dependencies"][extra]
    )
    return {normalise(re.split(r"[<>=!~\[;\s]", e, maxsplit=1)[0]) for e in entries}


def pinned(path: Path) -> set[str]:
    """The distribution names a compiled requirements file pins."""
    return {
        normalise(name) for name, _ in PIN.findall(path.read_text(encoding="utf-8"))
    }


def python_floor() -> str:
    """The lower bound of requires-python, e.g. "3.11"."""
    requires = pyproject()["project"]["requires-python"]
    match = re.search(r">=\s*(\d+\.\d+)", requires)
    assert match, f"requires-python has no lower bound to resolve against: {requires!r}"
    return match.group(1)


def compile_commands(path: Path) -> list[str]:
    return COMPILE_COMMAND.findall(path.read_text(encoding="utf-8"))


def header_command(path: Path) -> str:
    """The command uv records at the top of a file it generated.

    This is the artifact's own account of how it was made, which is why it is
    worth checking separately from the generators: a file regenerated by hand
    with the wrong flags passes every rule about the Makefile and fails here.
    """
    head = path.read_text(encoding="utf-8").split("\n", 4)[:4]
    for line in head:
        if "uv pip compile" in line:
            return line
    raise AssertionError(f"{path.name} carries no uv provenance header")


# --- The substantive rules -------------------------------------------------


def test_dev_requirements_pin_the_test_tooling():
    """`pip install -r requirements-dev.txt` must be able to run the suite.

    This is defect 1. docs/contributing.md's "Verify setup" step is `make test`,
    which is `python -m pytest`, so a dev requirements file without the `test`
    extra hands the contributor an environment that cannot do the thing the
    next documented line asks of it.
    """
    missing = declared(extra="test") - pinned(REQUIREMENTS_DEV)
    assert not missing, (
        "requirements/requirements-dev.txt pins no "
        f"{sorted(missing)} — the documented contributor install cannot run "
        "the test suite. Regenerate it with --extra dev --extra test."
    )


def test_dev_requirements_pin_the_dev_tooling():
    """The same loop for the lint tooling, which this file did carry."""
    missing = declared(extra="dev") - pinned(REQUIREMENTS_DEV)
    assert not missing, f"requirements/requirements-dev.txt pins no {sorted(missing)}"


def test_production_requirements_pin_every_core_dependency():
    """The production file must cover everything the app needs to start."""
    missing = declared() - pinned(REQUIREMENTS)
    assert not missing, f"requirements/requirements.txt pins no {sorted(missing)}"


def test_generators_compile_the_dev_file_with_both_extras():
    """Defect 1 cannot return through a regeneration.

    Fixing the artifact alone would have been undone by the next
    `make sync-deps`, so the rule is about the command, not the output.
    """
    for generator in GENERATORS:
        commands = [c for c in compile_commands(generator) if "requirements-dev" in c]
        assert commands, f"{generator.name} no longer generates requirements-dev.txt"
        for command in commands:
            assert "--extra dev" in command, f"{generator.name}: {command}"
            assert "--extra test" in command, (
                f"{generator.name} compiles requirements-dev.txt without "
                f"--extra test, so it will pin no test runner: {command}"
            )


def test_generators_pass_the_declared_python_floor():
    """Defect 2: --universal alone resolves from uv's own interpreter upwards.

    Without an explicit floor the output depends on the machine that ran the
    generator, which is precisely what --universal is there to prevent on the
    platform axis.
    """
    expected = f"--python-version {python_floor()}"
    for generator in GENERATORS:
        commands = compile_commands(generator)
        assert commands, f"{generator.name} no longer compiles any requirements file"
        for command in commands:
            assert expected in command, (
                f"{generator.name} compiles without {expected!r}, so --universal "
                f"will resolve from whatever interpreter uv picks: {command}"
            )


def test_generated_files_record_the_python_floor():
    """The artifacts' own provenance headers must agree with the generators.

    Checked separately so a hand-regenerated file cannot slip past the rules
    above, which only read the Makefile and the shell script.
    """
    expected = f"--python-version {python_floor()}"
    for path in (REQUIREMENTS, REQUIREMENTS_DEV):
        command = header_command(path)
        assert "--universal" in command, f"{path.name}: {command}"
        assert expected in command, (
            f"{path.name} was generated without {expected!r}, so it may have "
            f"dropped the pins that only exist below uv's interpreter: {command}"
        )
    assert "--extra test" in header_command(REQUIREMENTS_DEV)


# --- Guards on the guards --------------------------------------------------
#
# Every rule above is a set difference or a substring search, and both pass
# happily on an empty left-hand side. These three fail if the parsing has
# stopped matching, so a rule can never go quiet without a test going red.


def test_the_pyproject_parser_finds_the_declarations_it_compares():
    assert declared() >= {"streamlit", "requests"}
    assert len(declared(extra="test")) >= 3
    assert len(declared(extra="dev")) >= 2


def test_the_requirements_parsers_find_pins():
    for path in (REQUIREMENTS, REQUIREMENTS_DEV):
        assert (
            len(pinned(path)) >= 20
        ), f"{path.name} parsed as {len(pinned(path))} pins"
    assert len(pinned(REQUIREMENTS_DEV)) > len(pinned(REQUIREMENTS))


def test_the_generator_parser_finds_a_command_per_output_in_each_generator():
    for generator in GENERATORS:
        commands = compile_commands(generator)
        outputs = {
            match.group(1)
            for command in commands
            for match in [re.search(r"-o\s+(\S+)", command)]
            if match
        }
        assert outputs == {
            "requirements/requirements.txt",
            "requirements/requirements-dev.txt",
        }, f"{generator.name} compiles {sorted(outputs)}"
